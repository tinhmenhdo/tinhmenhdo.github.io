  /**
   * Format date thành YYYY-MM-DD HH:mm
   */
  static formatDateTime(date, includeSeconds = false) {
    const year = date.getUTCFullYear();
    const month = String(date.getUTCMonth() + 1).padStart(2, "0");
    const day = String(date.getUTCDate()).padStart(2, "0");
    const hours = String(date.getUTCHours()).padStart(2, "0");
    const minutes = String(date.getUTCMinutes()).padStart(2, "0");
    let res = `${year}/${month}/${day} ${hours}:${minutes}`;
    if (includeSeconds) {
      const seconds = String(date.getUTCSeconds()).padStart(2, "0");
      res += `:${seconds}`;
    }
    return res;
  }
  /**
   * Helper để lấy Date Object với các component (YMD Hms) tương ứng với Wall Clock Time (Giờ đồng hồ).
   * Date trả về sẽ có các component UTC khớp với giờ địa phương mong muốn.
   * Ví dụ: Input 10:30 (Local/UTC whatever) -> Output Date(UTC 10:30)
   */
  static getWallClockUtcDate(date) {
    const d = dayjs(date);
    return dayjs.utc().year(d.year()).month(d.month()).date(d.date()).hour(d.hour()).minute(d.minute()).second(d.second()).millisecond(0).toDate();
  }
